CREATE EXTENSION IF NOT EXISTS btree_gist;

-- auth.User (Django) ---------------------------------------------------------
CREATE TABLE auth_user (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password     varchar(128) NOT NULL,
    last_login   timestamptz  NULL,
    is_superuser boolean      NOT NULL,
    username     varchar(150) NOT NULL UNIQUE,
    first_name   varchar(150) NOT NULL,
    last_name    varchar(150) NOT NULL,
    email        varchar(254) NOT NULL,
    is_staff     boolean      NOT NULL,
    is_active    boolean      NOT NULL,
    date_joined  timestamptz  NOT NULL
);

-- spaces.Space ----------------------------------------------------------------
CREATE TABLE spaces_space (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL UNIQUE,
    kind varchar(10) NOT NULL,
    CONSTRAINT spaces_space_code_nonblank CHECK (code::text ~ '[^[:space:]]'),
    CONSTRAINT spaces_space_kind_valid    CHECK (kind IN ('room', 'laboratory'))
);

-- keys.Key --------------------------------------------------------------------
CREATE TABLE keys_key (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id bigint NOT NULL REFERENCES spaces_space (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX keys_key_space_id_idx ON keys_key (space_id);

-- keys.KeyLoan ----------------------------------------------------------------
CREATE TABLE keys_keyloan (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checked_out_at       timestamptz NOT NULL,
    returned_at          timestamptz NULL,
    checkout_operator_id integer NOT NULL REFERENCES auth_user (id) DEFERRABLE INITIALLY DEFERRED,
    key_id               bigint  NOT NULL REFERENCES keys_key (id)  DEFERRABLE INITIALLY DEFERRED,
    responsible_id       integer NOT NULL REFERENCES auth_user (id) DEFERRABLE INITIALLY DEFERRED,
    return_operator_id   integer NULL     REFERENCES auth_user (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT keys_return_not_before_checkout
        CHECK (returned_at IS NULL OR returned_at >= checked_out_at),
    CONSTRAINT keys_return_time_operator_together
        CHECK ((returned_at IS NULL AND return_operator_id IS NULL)
            OR (returned_at IS NOT NULL AND return_operator_id IS NOT NULL))
);
CREATE UNIQUE INDEX keys_one_active_loan_per_key ON keys_keyloan (key_id) WHERE returned_at IS NULL;
CREATE INDEX keys_keyloan_key_id_idx               ON keys_keyloan (key_id);
CREATE INDEX keys_keyloan_responsible_id_idx       ON keys_keyloan (responsible_id);
CREATE INDEX keys_keyloan_checkout_operator_id_idx ON keys_keyloan (checkout_operator_id);
CREATE INDEX keys_keyloan_return_operator_id_idx   ON keys_keyloan (return_operator_id);

-- keys.KeyMovement ------------------------------------------------------------
CREATE TABLE keys_keymovement (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        varchar(8)  NOT NULL,
    occurred_at timestamptz NOT NULL,
    loan_id     bigint  NOT NULL REFERENCES keys_keyloan (id) DEFERRABLE INITIALLY DEFERRED,
    operator_id integer NOT NULL REFERENCES auth_user (id)    DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT keys_movement_kind_valid        CHECK (kind IN ('checkout', 'return')),
    CONSTRAINT keys_one_movement_per_loan_kind UNIQUE (loan_id, kind)
);
CREATE INDEX keys_keymovement_operator_id_idx ON keys_keymovement (operator_id);

-- Triggers (RunSQL da migration keys/0001) ------------------------------------
CREATE FUNCTION keys_reject_space_change_after_loan() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.space_id IS DISTINCT FROM OLD.space_id
       AND EXISTS (SELECT 1 FROM keys_keyloan WHERE key_id = OLD.id) THEN
        RAISE EXCEPTION 'Key with loan history cannot change space'
            USING ERRCODE = '23514', CONSTRAINT = 'keys_key_space_fixed_after_loan';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER keys_key_space_fixed_after_loan
BEFORE UPDATE OF space_id ON keys_key
FOR EACH ROW EXECUTE FUNCTION keys_reject_space_change_after_loan();

CREATE FUNCTION keys_reject_movement_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Existing key movements cannot be changed'
        USING ERRCODE = '23514', CONSTRAINT = 'keys_movement_immutable';
END;
$$;
CREATE TRIGGER keys_movement_immutable
BEFORE UPDATE OR DELETE ON keys_keymovement
FOR EACH ROW EXECUTE FUNCTION keys_reject_movement_change();

-- bookings.Booking ------------------------------------------------------------
CREATE TABLE bookings_booking (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_at     timestamptz NOT NULL,
    end_at       timestamptz NOT NULL,
    status       varchar(9)  NOT NULL,
    created_at   timestamptz NOT NULL,
    cancelled_at timestamptz NULL,
    space_id     bigint  NOT NULL REFERENCES spaces_space (id) DEFERRABLE INITIALLY DEFERRED,
    user_id      integer NOT NULL REFERENCES auth_user (id)    DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT bookings_start_before_end CHECK (start_at < end_at),
    CONSTRAINT bookings_status_valid     CHECK (status IN ('active', 'cancelled')),
    CONSTRAINT bookings_cancelled_at_matches_status
        CHECK ((status = 'active' AND cancelled_at IS NULL)
            OR (status = 'cancelled' AND cancelled_at IS NOT NULL)),
    CONSTRAINT bookings_active_no_overlap
        EXCLUDE USING gist (space_id WITH =, tstzrange(start_at, end_at, '[)') WITH &&)
        WHERE (status = 'active')
);
CREATE INDEX bookings_booking_space_id_idx ON bookings_booking (space_id);
CREATE INDEX bookings_booking_user_id_idx  ON bookings_booking (user_id);
